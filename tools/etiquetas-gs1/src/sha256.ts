const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n))

export function sha256(datos: Uint8Array): Uint8Array {
  const largo = datos.length
  const bloques = Math.ceil((largo + 9) / 64)
  const m = new Uint8Array(bloques * 64)
  m.set(datos)
  m[largo] = 0x80
  const bits = largo * 8
  const vista = new DataView(m.buffer)
  vista.setUint32(m.length - 8, Math.floor(bits / 0x100000000))
  vista.setUint32(m.length - 4, bits >>> 0)
  const h = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19])
  const w = new Uint32Array(64)
  for (let b = 0; b < bloques; b++) {
    for (let i = 0; i < 16; i++) w[i] = vista.getUint32(b * 64 + i * 4)
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15]!, 7) ^ rotr(w[i - 15]!, 18) ^ (w[i - 15]! >>> 3)
      const s1 = rotr(w[i - 2]!, 17) ^ rotr(w[i - 2]!, 19) ^ (w[i - 2]! >>> 10)
      w[i] = (w[i - 16]! + s0 + w[i - 7]! + s1) >>> 0
    }
    let [a, bb, c, d, e, f, g, hh] = [h[0]!, h[1]!, h[2]!, h[3]!, h[4]!, h[5]!, h[6]!, h[7]!]
    for (let i = 0; i < 64; i++) {
      const t1 = (hh + (rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25)) + ((e & f) ^ (~e & g)) + K[i]! + w[i]!) >>> 0
      const t2 = ((rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22)) + ((a & bb) ^ (a & c) ^ (bb & c))) >>> 0
      hh = g; g = f; f = e; e = (d + t1) >>> 0; d = c; c = bb; bb = a; a = (t1 + t2) >>> 0
    }
    h[0] = (h[0]! + a) >>> 0; h[1] = (h[1]! + bb) >>> 0; h[2] = (h[2]! + c) >>> 0; h[3] = (h[3]! + d) >>> 0
    h[4] = (h[4]! + e) >>> 0; h[5] = (h[5]! + f) >>> 0; h[6] = (h[6]! + g) >>> 0; h[7] = (h[7]! + hh) >>> 0
  }
  const salida = new Uint8Array(32)
  const vs = new DataView(salida.buffer)
  for (let i = 0; i < 8; i++) vs.setUint32(i * 4, h[i]!)
  return salida
}

export const utf8 = (texto: string): Uint8Array => new TextEncoder().encode(texto)

export function aHex(b: Uint8Array): string {
  let s = ''
  for (const x of b) s += x.toString(16).padStart(2, '0')
  return s
}

export function deHex(hex: string): Uint8Array {
  if (!/^(?:[0-9a-f]{2})*$/i.test(hex)) throw new Error('hex invalido')
  const b = new Uint8Array(hex.length / 2)
  for (let i = 0; i < b.length; i++) b[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16)
  return b
}

/** Los hashes viajan autodescritos: `sha256:<64 hex>`. */
export const PREFIJO_HASH = 'sha256:'

export function comoHash(b: Uint8Array): string {
  return PREFIJO_HASH + aHex(b)
}

export function bytesDeHash(h: string): Uint8Array {
  if (!h.startsWith(PREFIJO_HASH) || h.length !== PREFIJO_HASH.length + 64) throw new Error(`hash mal formado: ${h.slice(0, 20)}`)
  return deHex(h.slice(PREFIJO_HASH.length))
}
